def generate(rng):
    xs = [("최소 X=1", 1), ("X=2", 2), ("X=3", 3), ("X=4", 4), ("X=5", 5), ("X=6", 6),
          ("X=7 (1 빼기가 필요)", 7), ("X=10", 10), ("X=11", 11), ("X=97 (소수)", 97),
          ("X=1024 (2의 거듭제곱)", 1024), ("X=15625 (5의 거듭제곱)", 15625), ("X=19683 (3의 거듭제곱)", 19683)]
    for i in range(5):
        xs.append((f"작은 랜덤 {i+1}", rng.randint(12, 300)))
    for i in range(3):
        xs.append((f"큰 랜덤 {i+1}", rng.randint(20000, 30000)))
    xs += [("최대 X=30000", 30000), ("X=29999", 29999), ("X=29989 (소수)", 29989)]
    return [{"name": n, "input": f"{x}\n"} for n, x in xs]
